"""情绪默认参数与情绪触发规则 —— **没有人格，也没有说话方式**。

「人格定制」「性格预设」「表达基调」这些功能已经整体删除，现在插件只做两件事：

1. **把"她此刻是什么心情"算出来**（PAD 数值 + 情绪标签 + 起因），
   连同记忆一起交给模型。
2. **绝不告诉模型她该怎么说话** —— 表达基调、语气、措辞、人设统统不注入，
   说话方式完全由机器人自己的人设提示词决定。

本模块因此只剩两样引擎还要读的东西：

- **情绪动力学默认值**：没事时心情停在哪里（气质基线）、情绪退得多快，
  以及**情绪强度的衰减策略**（策略 / 半衰期 / 衰减目标 / 冲击增益 / 初始强度）——
  强度是可单独调节的主动产物，配置 `emotion.intensity.*` 能覆盖这些默认值。
- **额外的情绪触发规则**：关系场景（被叫特别称呼、他生病了、他提别人……）
  该怎么"起反应" —— 只给情绪冲击与情绪标签，规则里不含任何"怎么说"的字样。
  想自己加规则，用配置里的 `emotion.persona.custom_rules`。

另有一组**自表达回读**的启发式（从她自己的回复反推情绪），
它只把结果写回情绪状态，同样不进提示词。
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .appraisal import Rule
from .model import PAD


@dataclass(frozen=True)
class Preset:
    """一套情绪参数。

    只描述"心情怎么动"：基线、衰减、心境联动、额外触发规则。
    **不含任何"怎么说话"的字段** —— style / style_overrides / style_note
    已随表达基调功能一起删除。
    """

    key: str
    label: str
    baseline: PAD
    emotion_half_life: float
    mood_half_life: float
    mood_coupling: float
    extra_rules: tuple[Rule, ...] = ()
    self_feedback: bool = True
    # ------------------------------------------------------------------
    # 情绪强度（独立、可调、会自己衰减的状态）的**衰减策略**
    # —— 配置 emotion.intensity.* 能覆盖它们；没配就用这里的默认值。
    # ------------------------------------------------------------------
    #: 衰减策略：exponential 指数 / linear 线性 / off 不衰减
    intensity_decay: str = "exponential"
    #: 强度半衰期（秒）：指数下每过这么久与目标的差距减半，
    #:                  线性下就是「回到目标要多久」
    intensity_half_life: float = 900.0
    #: 衰减目标（0~1）：没事时强度停在这里，不会掉到 0
    intensity_floor: float = 0.15
    #: 每次情绪冲击换算成多少强度（0~1 的增量比例）
    intensity_gain: float = 0.55
    #: 新会话 / 重置之后的初始强度（0~1）
    intensity_default: float = 0.30
    # ------------------------------------------------------------------
    # 心境（mood）的推进方式
    # ------------------------------------------------------------------
    #: 「对话还活着」的窗口（秒）：最近这段时间内有互动，心境才持续朝
    #: 「最近一次互动时的情绪」靠拢；窗口过了就只按半衰期自己回落。
    #: 不设这个窗口的话，对话一停情绪先衰减回基线，心境会被情绪拖回去，
    #: 下面的 mood_half_life 就白设了。
    mood_live_window: float = 1800.0
    #: 心境换词的驻留时间（秒）：新词要连续待够这么久才正式替换（防抖）
    mood_label_hold: float = 300.0


